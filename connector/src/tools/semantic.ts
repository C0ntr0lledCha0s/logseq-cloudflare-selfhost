function description(op: GraphOperation): string {
  const parts = [op.operation.summary ?? `${op.method} ${op.path}`];
  if (op.operation.description) parts.push(op.operation.description);
  if (HINTS[op.name]) parts.push(HINTS[op.name]);
  return parts.join("\n\n");
}

function syncErrorText(error: SyncError, alias: string, host: string): string {
  if (error.status === 401 || error.status === 403) {
    return `token for graph '${alias}' expired or lacks permission — reconnect it at https://${host}/graphs`;
  }
  if (error.status === 429) return `rate limited — retry after ${error.retryAfter ?? DEFAULT_RETRY_AFTER_S} s`;
  // 409 is a refusal the caller can act on, e.g. a title already in use or a delete that needs an
  // acknowledge-* flag; the server's message says what to do.
  if (error.status === 400 || error.status === 409) return error.message;
  return `sync server error (HTTP ${error.status}): ${error.message}`;
}

function queryParams(query: Record<string, unknown> | undefined): Record<string, string | number | boolean> | undefined {
  if (query === undefined) return undefined;
  const out: Record<string, string | number | boolean> = {};
  for (const [key, value] of Object.entries(query)) {
    if (typeof value !== "string" && typeof value !== "number" && typeof value !== "boolean") {
      throw new Error(`query parameter ${key} is not a scalar`);
    }
    out[key] = value;
  }
  return out;
}

/**
 * The graph behind `alias` for one tool call. Throws `ToolError` for an unknown alias, and for a
 * write on a read-only graph, before anything reaches the sync server.
 */
export async function resolveGraph(access: GraphAccess, alias: string, write: boolean): Promise<ResolvedGraph> {
  const graph = await access.resolve(alias);
  if (!graph) {
    throw new ToolError(`unknown graph '${alias}' — call list_graphs for the connected aliases`, "unknown-graph");
  }
  if (graph.mode !== "read" && graph.mode !== "write") throw new Error(`graph '${alias}' has an invalid mode`);
  if (graph.mode === "read" && write) throw new ToolError(`graph '${alias}' is read-only`, "read-only");
  return graph;
}

/** `syncFetch` for a tool call on `alias`: a sync server error becomes a `ToolError` with clear text. */
export async function graphFetch(access: GraphAccess, alias: string, pat: string, req: SyncRequest): Promise<Response> {
  try {
    return await syncFetch(access.env, pat, req);
  } catch (error) {
    if (!(error instanceof SyncError)) throw error;
    throw new ToolError(syncErrorText(error, alias, connectorHostname(access.env)), `http-${error.status}`);
  }
}

async function request(access: GraphAccess, req: UpstreamRequest): Promise<unknown> {
  const match = GRAPH_PATH.exec(req.path);
  // Upstream builds the path from the transformed spec, and the input schema enforces the alias pattern.
  if (!match || !ALIAS.test(match[1])) throw new Error("generated tool produced an unexpected path");
  const [, alias, rest] = match;
  for (const segment of rest.slice(1).split("/")) {
    if (segment === "") throw new ToolError("path arguments may not be empty", "refused");
    // Upstream percent-encodes each argument but leaves `.` and `..` as they are, and URL parsing
    // would collapse those into a different route.
    if ([".", ".."].includes(decodeURIComponent(segment))) {
      throw new ToolError("path arguments may not be '.' or '..'", "refused");
    }
  }
  const graph = await resolveGraph(access, alias, req.method !== "GET");
  const response = await graphFetch(access, alias, graph.pat, {
    method: req.method,
    path: `/api/v1/graphs/${encodeURIComponent(graph.graphId)}${rest}`,
    query: queryParams(req.query),
    json: req.body,
  });
  const text = await response.text();
  return text === "" ? null : JSON.parse(text);
}

/**
 * Builds one tool per graph operation of the sync server's OpenAPI `spec`. Nothing request-scoped is
 * captured: each call resolves its graph from the alias in its own path.
 */
export function buildGraphTools(spec: OpenApiSpec, access: GraphAccess): GraphTool[] {
  const operations = new Map(graphOperations(spec).map((op) => [op.operationId, op]));
  const tools = new Map<string, GraphTool>();
  // Upstream names each tool after its operationId and registers it on this recording proxy; the
  // recorded tool gets the snake_case name, the full description and the connector's annotations
  // (upstream's are derived from the HTTP method, which marks POST and PATCH writes that lose data
  // as non-destructive, so they are ignored).
  const recorder = {
    registerTool(
      operationId: string,
      config: { inputSchema: z.ZodRawShape },
      handler: UpstreamHandler,
    ): void {
      const op = operations.get(operationId);
      if (!op || tools.has(operationId)) throw new Error(`upstream registered an unexpected operation: ${operationId}`);
      const annotations = annotationsFor(op.name);
      // Every write takes the connector's own `reason`, which registerGraphTools strips before the
      // handler runs; an operation with an argument of that name would lose it.
      if (Object.hasOwn(config.inputSchema, "reason")) {
        throw new Error(`${operationId} already takes a reason argument; the connector's reason would hide it`);
      }
      const shape = annotations.readOnlyHint ? config.inputSchema : { ...config.inputSchema, reason: reasonSchema };
      tools.set(operationId, {
        name: op.name,
        config: {
          description: description(op),
          inputSchema: z.object(shape),
          annotations,
        },
        handler,
      });
    },
  };
  registerSemanticApiTools(recorder, transformSpec(spec), (req: UpstreamRequest) => request(access, req));
  if (tools.size !== operations.size) throw new Error("upstream did not register every graph operation");
  return [...tools.values()];
}

/**
 * Registers built graph tools on one request's server, with the connector's logging, error mapping
 * and result cap. `onSuccess` runs after each call the sync server accepted, with a write's reason
 * and the targets its response names. A write's `reason` is taken out of its arguments before the
 * handler sees them, so it never reaches the sync server. The result's first content item is a plain
 * summary: what the write touched, by page, breadcrumb and snippet, then the reason.
 */
export function registerGraphTools(server: McpServer, tools: GraphTool[], onSuccess: OnSuccess): void {
  for (const tool of tools) {
    const write = !tool.config.annotations.readOnlyHint;
    server.registerTool(tool.name, tool.config, (args) => {
      const alias = aliasArg(args);
      return runTool(
        tool.name,
        alias,
        async () => {
          const { reason, rest } = write ? takeReason(args) : { reason: undefined, rest: args };
          const result = await tool.handler(rest);
          // The input schema requires a well-formed alias, so a call that got this far has one.
          if (alias === undefined) throw new Error("graph tool ran without a valid alias");
          if (!write) {
            onSuccess(tool.name, alias);
            return result;
          }
          const { targets, summary } = describeWrite(tool.name, result, reason);
          onSuccess(tool.name, alias, { reason, targets });
          return capWriteResult(withSummary(result, summary));
        },
        write ? reasonGiven(args) : undefined,
      );
    });
  }
}

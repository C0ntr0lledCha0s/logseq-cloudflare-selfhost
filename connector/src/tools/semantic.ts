// One MCP tool per sync-server operation, generated by upstream's `registerSemanticApiTools` from the
// transformed spec. Upstream substitutes the `graph` alias into the path; `request` below maps it to
// the graph's ID and PAT, enforces read-only graphs and calls the sync server over the SYNC binding.
// Building the tools (JSON Schema → zod) is the expensive part, so it happens once per isolate
// (`buildGraphTools`); each request only registers the built tools on its own fresh server.

export interface GraphAccess {
  env: Env;
  /** The graph behind an alias, read in one query; null for an unknown alias. */
  resolve(alias: string): Promise<ResolvedGraph | null>;
}

/** A generated tool, ready to register. Its handler throws `ToolError` for refusals and mapped errors. */
export interface GraphTool {
  name: string;
  config: { description: string; inputSchema: z.ZodObject<z.ZodRawShape>; annotations: ToolAnnotations };
  handler: UpstreamHandler;
}

/** What upstream's tool handlers pass to `request`: the path already has every argument substituted. */
interface UpstreamRequest {
  method: string;
  path: string;
  query?: Record<string, unknown>;
  body?: unknown;
}

type UpstreamHandler = (args: Record<string, unknown>) => Promise<CallToolResult>;

const ALIAS = new RegExp(ALIAS_PATTERN);
const GRAPH_PATH = /^\/api\/v1\/graphs\/([^/]+)(\/.*)$/;
const DEFAULT_RETRY_AFTER_S = 60;

/** The request header that asks the sync server to stamp a write's blocks as Claude's (patch 0034). */
const EDIT_STAMP_HEADER = "x-logseq-edit-stamp";

/**
 * Headers for a sync request on `graph`: `x-logseq-edit-stamp: claude` on every non-GET when the
 * graph's edit stamps are on (design 2026-11-07-claude-edit-stamps-editedby §3.4). GETs, including
 * the audit log's before-snapshot reads, never carry it.
 */
export function editStampHeaders(graph: ResolvedGraph, method: string): Record<string, string> {
  return method !== "GET" && graph.editStamps ? { [EDIT_STAMP_HEADER]: "claude" } : {};
}

